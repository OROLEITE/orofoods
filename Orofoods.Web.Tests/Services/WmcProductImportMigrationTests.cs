namespace Orofoods.Web.Tests.Services;

public sealed class WmcProductImportMigrationTests
{
    [Fact]
    public async Task Sqlite_migration_stream_applies_to_a_disposable_database()
    {
        await using var connection = new SqliteConnection("Data Source=:memory:");
        await connection.OpenAsync();
        var options = new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseSqlite(connection)
            .ConfigureWarnings(warnings => warnings.Ignore(RelationalEventId.PendingModelChangesWarning))
            .Options;
        await using var db = new ApplicationDbContext(options);

        await db.Database.MigrateAsync();

        var tables = new List<string>();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT name FROM sqlite_master WHERE type = 'table'";
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync()) tables.Add(reader.GetString(0));

        Assert.Contains("WmcProductImportAudits", tables);
        Assert.Contains("WmcProductUnits", tables);
    }

    [Fact]
    public void Sqlite_import_audit_migration_has_expected_columns_and_index_without_applying()
    {
        var migration = new AddWmcProductImportAuditSqlite();
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        var index = Assert.Single(migration.UpOperations.OfType<CreateIndexOperation>());

        Assert.Equal("WmcProductImportAudits", table.Name);
        Assert.Equal("INTEGER", table.Columns.Single(c => c.Name == "BrandCode").ColumnType);
        Assert.Equal("TEXT", table.Columns.Single(c => c.Name == "ResultsJson").ColumnType);
        Assert.Equal("INTEGER", table.Columns.Single(c => c.Name == "Id").ColumnType);
        Assert.True(table.Columns.Single(c => c.Name == "ResultsJson").IsNullable is false);
        Assert.Equal("IX_WmcProductImportAudits_CompletedAt", index.Name);
        Assert.Equal("CompletedAt", Assert.Single(index.Columns));
        var options = new DbContextOptionsBuilder<ApplicationDbContext>().UseSqlite("Data Source=:memory:").Options;
        using var db = new ApplicationDbContext(options);
        var sql = string.Join(Environment.NewLine, db.GetService<IMigrationsSqlGenerator>().Generate(migration.UpOperations, migration.TargetModel).Select(command => command.CommandText));
        Assert.Contains("CREATE TABLE \"WmcProductImportAudits\"", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("PRIMARY KEY AUTOINCREMENT", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("CREATE INDEX \"IX_WmcProductImportAudits_CompletedAt\"", sql, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void Postgresql_import_audit_migration_has_expected_types_identity_and_index_without_applying()
    {
        var migration = new AddWmcProductImportAudit();
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        var index = Assert.Single(migration.UpOperations.OfType<CreateIndexOperation>());

        Assert.Equal("WmcProductImportAudits", table.Name);
        Assert.Equal("smallint", table.Columns.Single(c => c.Name == "BrandCode").ColumnType);
        Assert.Equal("timestamp without time zone", table.Columns.Single(c => c.Name == "StartedAt").ColumnType);
        Assert.Equal("timestamp without time zone", table.Columns.Single(c => c.Name == "CompletedAt").ColumnType);
        Assert.Equal("text", table.Columns.Single(c => c.Name == "ResultsJson").ColumnType);
        Assert.Equal("IX_WmcProductImportAudits_CompletedAt", index.Name);
        Assert.Equal("CompletedAt", Assert.Single(index.Columns));
        var options = new DbContextOptionsBuilder<PostgreSqlApplicationDbContext>().UseNpgsql("Host=127.0.0.1;Database=unused;Username=unused").Options;
        using var db = new PostgreSqlApplicationDbContext(options);
        var sql = string.Join(Environment.NewLine, db.GetService<IMigrationsSqlGenerator>().Generate(migration.UpOperations, migration.TargetModel).Select(command => command.CommandText));
        Assert.Contains("CREATE TABLE \"WmcProductImportAudits\"", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("smallint", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("timestamp without time zone", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("CREATE INDEX \"IX_WmcProductImportAudits_CompletedAt\"", sql, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void Sqlite_product_units_migration_uses_product_and_unit_as_key_and_cascades_without_applying()
    {
        var migration = new AddWmcProductUnitsSqlite();
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());

        Assert.Equal("WmcProductUnits", table.Name);
        Assert.Equal(["ProductId", "UnitCode"], table.PrimaryKey!.Columns);
        Assert.Equal("TEXT", table.Columns.Single(c => c.Name == "Factor").ColumnType);
        Assert.Equal("TEXT", table.Columns.Single(c => c.Name == "Barcode").ColumnType);
        Assert.Equal("Products", Assert.Single(table.ForeignKeys).PrincipalTable);
        Assert.Equal("Cascade", Assert.Single(table.ForeignKeys).OnDelete.ToString());

        var options = new DbContextOptionsBuilder<ApplicationDbContext>().UseSqlite("Data Source=:memory:").Options;
        using var db = new ApplicationDbContext(options);
        var sql = string.Join(Environment.NewLine, db.GetService<IMigrationsSqlGenerator>().Generate(migration.UpOperations, migration.TargetModel).Select(command => command.CommandText));
        Assert.Contains("CREATE TABLE \"WmcProductUnits\"", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("PRIMARY KEY (\"ProductId\", \"UnitCode\")", sql, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("ON DELETE CASCADE", sql, StringComparison.OrdinalIgnoreCase);
    }

